"""The saved state as it is in memory before any game: tools/extract_fresh.py src/fresh_save.c"""
import os, sys
sys.path.insert(0, os.path.dirname(__file__))
from oracle import Emu, ORIG

emu = Emu(os.path.join(ORIG, 'CIV.EXE'))
emu.reset()
data = emu.save_bytes()
out = ['/* Generated by tools/extract_fresh.py -- do not edit.  The saved variables as the EXE',
       ' * loads them, before any game: a new game starts from here. */',
       '#include <stdint.h>', '',
       'const uint8_t fresh_save[%d] = {' % len(data)]
for i in range(0, len(data), 24):
    out.append('    ' + ','.join(str(b) for b in data[i:i + 24]) + ',')
out += ['};', '']
open(sys.argv[1], 'w').write('\n'.join(out))
