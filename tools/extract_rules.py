"""Extract the game-rule tables from CIV.EXE's data segment and emit C source.

Usage: python3 -I tools/extract_rules.py ~/Dos/Civ1/CIV.EXE src/rules_data.c
All addresses are offsets into DGROUP (segment 0x2a1b of the unpacked image).
"""
import struct, sys, os
sys.path.insert(0, os.path.dirname(__file__))
from unexepack import unpack

DGROUP = 0x2a1b * 16

def load_dgroup(path):
    exe, _ = unpack(open(path, 'rb').read())
    hdr = struct.unpack('<H', exe[8:10])[0] * 16
    return exe[hdr + DGROUP:]

def cstr(b):
    return b.split(b'\0')[0].decode('latin1')

def q(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'

def table(ds, off, size, count):
    return [ds[off + i * size:off + (i + 1) * size] for i in range(count)]

def strings(ds, off, n):
    out = []
    for _ in range(n):
        s = cstr(ds[off:]); out.append(s); off += len(s) + 1
    return out

def main(exe, dst):
    ds = load_dgroup(exe)
    o = ['/* Generated by tools/extract_rules.py from CIV.EXE DGROUP -- do not edit. */',
         '#include "rules.h"', '']

    o.append('const char *const government_names[NUM_GOVERNMENTS] = {')
    o += ['    %s,' % q(s) for s in strings(ds, 0x00ac, 6)] + ['};', '']
    o.append('const char *const trade_good_names[NUM_TRADE_GOODS] = {')
    o += ['    %s,' % q(s) for s in strings(ds, 0x00e5, 8)] + ['};', '']
    o.append('const char *const leader_titles[NUM_GOVERNMENTS] = {')
    o += ['    %s,' % q(s) for s in strings(ds, 0x0239, 6)] + ['};', '']

    o.append('/* Index -1 is what the original reads for terrain -1 (a square off the map): the 19')
    o.append(' * bytes before the table.  terrain_types (rules.h) points one past it. */')
    o.append('const TerrainType terrain_types_ext[NUM_TERRAIN_TYPES + 1] = {')
    o.append('    /* name, move, defense(x0.5), food, shields, trade, unk7, map colour */')
    for rec in table(ds, 0x0282 - 19, 19, NUM_TERRAIN + 1):
        o.append('    {%-12s %d, %d, %d, %d, %d, %d, %2d},' % (q(cstr(rec[:12])) + ',', *rec[12:19]))
    o += ['};', '']

    o.append('const AdvanceType advance_types[NUM_ADVANCES] = {')
    o.append('    /* name, prereq1, prereq2  (-1 = none, 127 = unreachable) */')
    for i, rec in enumerate(table(ds, 0x04da, 22, NUM_ADVANCES)):
        p1, p2 = struct.unpack('<bb', rec[20:22])
        o.append('    {%-22s {%3d, %3d}},  /* %2d */' % (q(cstr(rec[:20])) + ',', p1, p2, i))
    o += ['};', '']

    o.append('const BuildingType building_types[NUM_BUILDINGS] = {')
    o.append('    /* name, cost (x10 shields), upkeep, prereq advance */')
    for i, rec in enumerate(table(ds, 0x0b9a, 30, NUM_BUILDINGS)):
        c, u, p = struct.unpack('<hhh', rec[24:30])
        o.append('    {%-26s %2d, %d, %3d},  /* %2d */' % (q(cstr(rec[:24])) + ',', c, u, p, i))
    o += ['};', '']

    o.append('const UnitType unit_types[NUM_UNIT_TYPES] = {')
    o.append('    /* name, obsolete_by, domain, moves, fuel, attack, defense, cost, sight, capacity, role, prereq */')
    for i, rec in enumerate(table(ds, 0x112a, 34, NUM_UNITS)):
        f = struct.unpack('<11h', rec[12:34])
        o.append('    {%-13s %3d, %d, %2d, %d, %2d, %2d, %2d, %d, %d, %d, %3d},  /* %2d */' % (q(cstr(rec[:12])) + ',', *f, i))
    o += ['};', '']

    o.append('/* DGROUP 0x044A: per base terrain; negative effect -n means +(n-1) yield, a value >= 0')
    o.append(' * converts the square to the terrain with that map colour. */')
    o.append('const TerrainImprove terrain_improve[12] = {')
    o.append('    /* irrigate, turns, mine, turns, unk4, unk5 */')
    for t, rec in enumerate(table(ds, 0x044a, 12, 12)):
        o.append('    {%3d, %2d, %3d, %2d, %d, %d},  /* %s */' % (*struct.unpack('<6h', rec), cstr(ds[0x282 + 19 * t:0x282 + 19 * t + 12])))
    o += ['};', '']

    o.append('/* DGROUP 0x10FE: advance that makes each wonder obsolete (index = wonder, 1-21). */')
    o.append('const signed char wonder_obsolete[NUM_WONDERS + 1] = {')
    o.append('    ' + ', '.join('%d' % v for v in struct.unpack('<22h', ds[0x10fe:0x10fe + 44])))
    o += ['};', '']

    def words(off, n):
        return ', '.join('%d' % v for v in struct.unpack('<%dh' % n, ds[off:off + 2 * n]))
    o.append('/* DGROUP 0x1882 / 0x18E4: the square itself, its 8 neighbours, then the next two rings. */')
    o.append('const signed char around_dx[49] = { %s };' % words(0x1882, 49))
    o.append('const signed char around_dy[49] = { %s };' % words(0x18e4, 49))
    o.append('')
    o.append('/* DGROUP 0x2498 / 0x24C2: the 21 squares of a city radius; index 20 is the city. */')
    o.append('const signed char city_square_dx[21] = { %s };' % words(0x2498, 21))
    o.append('const signed char city_square_dy[21] = { %s };' % words(0x24c2, 21))
    o.append('')
    o.append('/* DGROUP 0x2B56: map colour -> terrain type (-1 = unused colour). */')
    o.append('const signed char terrain_by_colour[16] = { %s };' % words(0x2b56, 16))
    o.append('')

    o.append('/* DGROUP 0x0B0A: AI appetite for each advance: base + science bias * weight. */')
    o.append('const signed char advance_ai[NUM_ADVANCES][2] = {')
    o.append('    ' + ', '.join('{%d, %d}' % struct.unpack('<2b', ds[0x0b0a + 2 * i:0x0b0c + 2 * i]) for i in range(72)))
    o += ['};', '']

    o.append('/* DGROUP 0x358A: start square of each civilization on the Earth map. */')
    o.append('const signed char earth_start[NUM_CIV_TYPES][2] = {')
    o.append('    ' + ', '.join('{%d, %d}' % (struct.unpack('<b', ds[0x358a + 2 * i:0x358b + 2 * i])[0],
                                              struct.unpack('<b', ds[0x358b + 2 * i:0x358c + 2 * i])[0]) for i in range(16)))
    o += ['};', '']

    o.append('/* Index -1 is what the original reads for the barbarians (civ type -1): the 58 bytes')
    o.append(' * before the table.  Use civ_type_info(). */')
    o.append('const CivType civ_types_ext[NUM_CIV_TYPES + 1] = {')
    o.append('    /* leader, plural, adjective, aggression, unk1, science bias, music, unk4 */')
    for rec in table(ds, 0x14e2 - 58, 58, NUM_CIVS + 1):
        f = struct.unpack('<5h', rec[48:58])
        o.append('    {%-14s %-10s %-13s %2d, %2d, %2d, %2d, %2d},' % (
            q(cstr(rec[0:16])) + ',', q(cstr(rec[16:32])) + ',', q(cstr(rec[32:48])) + ',', *f))
    o += ['};', '']

    o.append('/* Older 8-civ name lists (DGROUP 0x0111..0x0238, space padded); not yet seen referenced. */')
    o.append('const char *const civ_short_names[8] = {')
    o += ['    %s,' % q(s) for s in strings(ds, 0x0111, 8)] + ['};', '']
    o.append('const char *const civ_plural_names[8] = {')
    o += ['    %s,' % q(s) for s in strings(ds, 0x0169, 8)] + ['};', '']
    o.append('const char *const civ_leader_names[8] = {')
    o += ['    %s,' % q(s) for s in strings(ds, 0x01c9, 8)] + ['};', '']

    o.append('/* The initialised part of DGROUP as the EXE ships it, for the few places where the')
    o.append(' * original reads a table out of range (see dgroup_word() in rules.h). */')
    o.append('const unsigned char dgroup_init[DGROUP_INIT_SIZE] = {')
    init = ds[:0x6ab0]
    for i in range(0, len(init), 24):
        o.append('    ' + ','.join(str(b) for b in init[i:i + 24]) + ',')
    o += ['};', '']

    open(dst, 'w').write('\n'.join(o))

NUM_TERRAIN, NUM_ADVANCES, NUM_BUILDINGS, NUM_UNITS, NUM_CIVS = 24, 72, 46, 28, 16

if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
